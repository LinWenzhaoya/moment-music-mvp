const findTrack = db.prepare("SELECT title, artist FROM tracks WHERE id=? AND available=1");
const duplicates = db.prepare("SELECT id FROM tracks WHERE available=1 AND lower(trim(title))=lower(trim(?)) AND lower(trim(artist))=lower(trim(?))");
const insert = db.prepare(`INSERT INTO song_experience_profiles
  (track_id, style_json, felt_json, energy_json, sound_json, identity_text, avoid_text, source, review_status, notes)
  VALUES (?, ?, ?, ?, ?, ?, ?, 'codex_curated', 'needs_user_review', 'batch-01')
  ON CONFLICT(track_id) DO NOTHING`);

let inserted = 0;
db.exec("BEGIN");
try {
  for (const profile of profiles) {
    const track = findTrack.get(profile.id);
    if (!track) continue;
    for (const duplicate of duplicates.all(track.title, track.artist)) {
      const result = insert.run(duplicate.id, JSON.stringify(profile.style), JSON.stringify(profile.felt), JSON.stringify(profile.energy), JSON.stringify(profile.sound), profile.identity, profile.avoid);
      inserted += Number(result.changes || 0);
    }
  }
  db.exec("COMMIT");
} catch (error) {
  db.exec("ROLLBACK");
  throw error;
}

console.log(`Batch 01: ${profiles.length} canonical profiles, ${inserted} track profiles inserted.`);
